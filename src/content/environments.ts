/**
 * Depositional environments and their diagnostic rules (BUMILAPIS.md Bagian 3.F).
 * Rule values use the ids of content/vocab.ts and content/lithologies.ts; grain size uses the
 * groups of `grainGroup` below. Weights (1–5) are teaching judgements, not measurements.
 */
export type GrainGroup = 'mud' | 'fine-sand' | 'medium-sand' | 'coarse-sand' | 'gravel';
export const grainGroupNames: Record<GrainGroup, string> = {
  mud: 'lempung–lanau',
  'fine-sand': 'pasir halus',
  'medium-sand': 'pasir sedang',
  'coarse-sand': 'pasir kasar',
  gravel: 'kerikil atau lebih kasar',
};
export function grainGroup(g: GrainSize): GrainGroup {
  if (g === 'clay' || g === 'silt') return 'mud';
  if (g === 'vf-sand' || g === 'f-sand') return 'fine-sand';
  if (g === 'm-sand') return 'medium-sand';
  if (g === 'c-sand' || g === 'vc-sand') return 'coarse-sand';
  return 'gravel';
}

const r = (feature: ObservationFeature, value: string, weight: number, note: string, diagnostic = false): Rule => ({ feature, value, weight, note, ...(diagnostic ? { diagnostic } : {}) });
let bedSeq = 0;
const bed = (thicknessM: number, lithologyId: string, grainSize: GrainSize, opts: Partial<Bed> = {}): Omit<Bed, 'topM' | 'baseM'> & { thicknessM: number } => ({
  id: `t${++bedSeq}`,
  thicknessM,
  lithologyId,
  grainSize,
  structures: [],
  fossils: [],
  baseContact: 'gradational',
  ...opts,
});
/** Stack beds listed from top to bottom into a mini column. */
function succession(list: ReturnType<typeof bed>[]): Bed[] {
  let top = 0;
  return list.map(({ thicknessM, ...b }) => {
    const out = { ...b, topM: top, baseM: top + thicknessM } as Bed;
    top += thicknessM;
    return out;
  });
}
