export const layerById = new Map(layers.map((l) => [l.id, l]));

export type GroupingMode = 'compositional' | 'mechanical';

/** Interior layers that form the concentric shells for a grouping mode (outermost first). */
export function interiorShells(mode: GroupingMode): EarthLayer[] {
  return layers.filter(
    (l) => l.realm === 'interior' && !l.variantOf && (l.grouping === mode || l.grouping === 'both'),
  );
}

export const atmosphereShells: EarthLayer[] = layers.filter((l) => l.realm === 'atmosphere');

/** Layers visible in the list for a grouping mode, top to bottom. */
export function layerList(mode: GroupingMode): EarthLayer[] {
  return layers
    .filter((l) => l.realm !== 'interior' || l.grouping === mode || l.grouping === 'both')
    .map((l, i) => ({ l, i }))
    .sort((a, b) => (a.l.realm === 'interior' || b.l.realm === 'interior' ? a.i - b.i : b.l.topKm - a.l.topKm || a.i - b.i))
    .map((x) => x.l);
}

